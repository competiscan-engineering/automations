def _period_window():
    """Returns (start, end). Explicit env overrides win; otherwise the configured
    cadence and anchor decide. prior_complete is reproducible — re-running next
    Tuesday gives the same window."""
    if PERIOD_START:
        s = date.fromisoformat(PERIOD_START)
        e = date.fromisoformat(PERIOD_END) if PERIOD_END else (
            s + timedelta(days=7) if PERIOD_KIND == "week" else _month_end(s))
        return s, e
    today = date.today()
    if PERIOD_KIND == "week":
        if PERIOD_ANCHOR == "rolling":
            return today - timedelta(days=7), today
        this_monday = today - timedelta(days=today.weekday())
        return this_monday - timedelta(days=7), this_monday
    if PERIOD_ANCHOR == "rolling":
        return today - timedelta(days=30), today
    first_this = today.replace(day=1)
    prev_end = first_this - timedelta(days=1)
    return prev_end.replace(day=1), prev_end


def _month_end(d):
    nxt = (d.replace(day=28) + timedelta(days=4)).replace(day=1)
    return nxt - timedelta(days=1)


def _ordinal(n):
    return f"{n}{'th' if 11 <= n % 100 <= 13 else {1: 'st', 2: 'nd', 3: 'rd'}.get(n % 10, 'th')}"


def _entry_date(entry_id):
    """entry_id is YYYY-MM-DD-NNNN. This is the MAILED/CAPTURED date, which is
    NOT approved_date and NOT added_to_database."""
    try:
        y, m, d = str(entry_id).split("-")[:3]
        return date(int(y), int(m), int(d))
    except (ValueError, AttributeError):
        return None


def _dedup(records):
    seen, out = set(), []
    for r in records:
        eid = r.get("entry_id")
        if eid and eid not in seen:
            seen.add(eid)
            out.append(r)
    return out


def _theme_key(record):
    """Coarse creative fingerprint: company + the first few headline words. Stops a
    company that reused one evergreen creative from filling every image slot."""
    co = (record.get("company_name") or "").lower().strip()
    head = re.sub(r"[^a-z0-9 ]", "", (record.get("headline") or "").lower())
    return f"{co}|{' '.join(head.split()[:6])}"


def _apply_filters(records, group, subcats_by_id=None):
    """Preset hard-filters, in graph order. Every one of these came from a shipped
    pipeline; none of them ask the model to do the filtering."""
    out = list(records)
    for f in group.get("filters", []):
        p = f["preset"]
        before = len(out)
        if p == "cu_only":
            out = [r for r in out if _CU_RE.search(r.get("company_name") or "")]
        elif p == "name_regex":
            inc, exc = f.get("include") or "", f.get("exclude") or ""
            if inc:
                out = [r for r in out
                       if re.search(inc, r.get("company_name") or "", re.I)]
            if exc:
                out = [r for r in out
                       if not re.search(exc, r.get("company_name") or "", re.I)]
        elif p == "subcategory":
            inc, exc = f.get("include") or [], f.get("exclude") or []
            kept = []
            for r in out:
                tags = (subcats_by_id or {}).get(r.get("entry_id"), "").lower()
                # A blank tag matches NOTHING: dropping an unverifiable entry beats
                # putting it on the wrong slide.
                if not tags:
                    continue
                if any(k in tags for k in exc):
                    continue
                if inc and not any(k in tags for k in inc):
                    continue
                kept.append(r)
            out = kept
        elif p == "creative_dedupe":
            cap, counts, kept = f.get("max_per_theme", 2), {}, []
            for r in out:
                k = _theme_key(r)
                if counts.get(k, 0) < cap:
                    counts[k] = counts.get(k, 0) + 1
                    kept.append(r)
            out = kept
        if len(out) != before:
            print(f"      filter {p}: {before} -> {len(out)}")
    return out


def _run_search(group, channel, limit):
    """ONE call, ONE channel. Fanning out per channel multiplies the per-call cap.
    Callers must keep this sequential (see the module docstring)."""
    kwargs = {"media_channels": [channel], "limit": limit}
    if group["sectors"]:
        kwargs["sectors"] = group["sectors"]
    if group["company_names"]:
        kwargs["company_names"] = group["company_names"]
    if group["keyword"]:
        kwargs["keyword"] = group["keyword"]
    if group["audience"]:
        kwargs["audience"] = group["audience"]
    try:
        res = search_archive(**kwargs)
    except Exception as exc:  # a dead VPN must not kill the whole run
        return [], False, str(exc)
    if res and isinstance(res[0], dict) and "error" in res[0]:
        return [], False, res[0]["error"]
    rows = [r for r in (res or []) if r.get("entry_id")]
    return rows, len(rows) >= limit, None


# ── Prompts ──────────────────────────────────────────────────────────────────
SELECT_SYSTEM = (
    "You are a competitive-intelligence analyst choosing which archive pieces to "
    "feature on a client slide.\n\n"
    "RULES\n"
    "- Work ONLY from the OCR text supplied. Never invent an offer, rate or detail.\n"
    "- Choose from the candidate entry_ids given. Do not output any other id.\n"
    "- Prefer variety: different institutions and different offers beat near-"
    "duplicates.\n\n"
    "SLIDE GUIDANCE\n{guidance}\n\n"
    'Reply with ONE JSON object: {{"entry_ids": ["..."], "reasoning": "one line"}}'
)

CALLOUT_SYSTEM = (
    "You are writing the callout paragraph for a client-facing slide.\n\n"
    "RULES\n"
    "- Describe ONLY the pieces supplied. Never invent details.\n"
    "- Under {limit} characters. Whole sentences.\n"
    "- Analyst voice. No bullet points, no preamble.\n\n"
    "STYLE\n{style}\n\n"
    'Reply with ONE JSON object: {{"callout": "..."}}'
)


def _shortlist(records):
    """Compact candidate view. OCR is truncated hard — the model needs enough to
    judge relevance, not the whole document."""
    lines = []
    for r in records:
        lines.append(
            f'- {r.get("entry_id")} | {r.get("company_name") or "?"} | '
            f'{r.get("media_channel") or "?"} | {(r.get("state") or "")} | '
            f'{L.clean_cell(r.get("headline"))[:180]} | '
            f'{L.clean_cell(r.get("ocr_text"))[:400]}'
        )
    return "\n".join(lines)


def _select(group, records):
    if not records:
        return {"entry_ids": []}
    system = SELECT_SYSTEM.replace("{guidance}", group.get("guidance") or "None.")
    prompt = (f'Choose up to {group["want"]} pieces for the "{group["title"]}" '
              f'slide.\n\nCANDIDATES\n{_shortlist(records)}')
    try:
        return L.extract_json(L.call_claude(system, prompt))
    except Exception as exc:
        return {"error": str(exc), "entry_ids": []}


def _callout(group, chosen, true_count, cap_hit):
    if not chosen:
        return {"callout": ""}
    limit = group.get("callout_limit", 374)
    system = (CALLOUT_SYSTEM.replace("{limit}", str(limit))
              .replace("{style}", group.get("narrative_style") or "Plain analyst prose."))
    # The count is computed in Python and STATED to the model. A capped search
    # means the true total is unknown, so the model must say "at least N".
    count_note = (f"At least {true_count} pieces were found (the search hit its "
                  f"result cap, so the true total is higher). Phrase it as 'at "
                  f"least {true_count}'." if cap_hit else
                  f"Exactly {true_count} piece(s) were found this period.")
    prompt = (f'Slide: "{group["title"]}".\n{count_note}\n\n'
              f'FEATURED PIECES\n{_shortlist(chosen)}')
    try:
        return L.extract_json(L.call_claude(system, prompt))
    except Exception as exc:
        return {"error": str(exc), "callout": ""}


def _synthesize(period_label, findings):
    """The LAST model call. It reads the FINISHED callouts rather than raw OCR —
    cheaper, and it cannot contradict what the deck already says."""
    prompt = (f"Period: {period_label}\n\nFINDINGS ALREADY WRITTEN INTO THE DECK\n"
              + "\n".join(findings)
              + '\n\nReply with ONE JSON object: '
                '{"column1": "...", "column2": "..."}')
    try:
        return L.extract_json(L.call_claude(SYNTH_SYSTEM, prompt))
    except Exception as exc:
        return {"error": str(exc)}


# ── Pipeline ─────────────────────────────────────────────────────────────────
def main() -> int:
    args = _parse_args()
    start, end = _period_window()
    period_label = f"{start:%B} {start.year}"
    stamp = end.strftime("%Y%m%d")
    mmddyy = end.strftime("%m%d%y")
    month_year = f"{start:%B}{start.year}"
    OUTPUT_DIR.mkdir(parents=True, exist_ok=True)
    print(f"{CLIENT} — {period_label}")
    print(f"  window {start} .. {end}  (bounded by entry_id)")
    print(f"  mode --only={args.only}"
          + (f" --limit={args.limit}" if args.limit else ""))

    # ── Step 1 — search, SEQUENTIALLY (see docstring guardrail) ─────────────
    total_calls = sum(len(g["channels"]) for g in GROUPS)
    print(f"\nStep 1  Searching ({total_calls} group x channel calls, sequential)…")
    found = {}
    for group in GROUPS:
        limit = args.limit or group["limit"]
        records, cap_hit, err = [], False, None
        for channel in group["channels"]:
            rows, hit, e = _run_search(group, channel, limit)
            if e:
                err = e
                print(f"   ! {group['title']} / {channel}: {e}")
                continue
            records.extend(rows)
            cap_hit = cap_hit or hit
        raw_n = len(records)
        records = _dedup(records)
        in_window = []
        for r in records:
            d = _entry_date(r.get("entry_id"))
            if d and start <= d <= end:
                in_window.append(r)
        print(f"   {group['title'][:34]:34} {raw_n:>4} raw"
              f"{' (CAP HIT)' if cap_hit else '':10} -> {len(in_window):>4} in window")
        if cap_hit and not in_window:
            # All capped records missed the window: implausible for a real company.
            print(f"   !! SUSPECT: {group['title']} hit the cap but 0 landed in the "
                  f"window. This is probably NOT a true zero — verify in PowerSearch "
                  f"before reporting it.")
        found[group["key"]] = {"group": group, "records": in_window,
                              "cap_hit": cap_hit, "error": err}

    if not any(v["records"] for v in found.values()):
        print("\nERROR: every group came back empty. Is the VPN up and the archive "
              "reachable? Aborting rather than shipping an empty report.")
        return 1

    enriched, subcats_by_id = {}, {}

    # ── Step 3 — preset hard-filters ────────────────────────────────────────
    print("\nStep 3  Applying filters…")
    for key, v in found.items():
        if not v["group"].get("filters"):
            continue
        print(f"   {v['group']['title']}")
        v["records"] = _apply_filters(v["records"], v["group"], subcats_by_id)

    if args.only == "search":
        print("\n── Counts (sanity-check against PowerSearch) ──")
        for key, v in found.items():
            n = len(v["records"])
            print(f"   {v['group']['title'][:38]:38} "
                  f"{'at least ' if v['cap_hit'] else ''}{n}")
        return 0

    xlsx_path = None

    # ── Step 5 — selection, in parallel (Bedrock handles concurrency fine;
    #             it is only the archive REST layer that must stay sequential) ──
    curated = [g for g in GROUPS if g.get("want")]
    print(f"\nStep 5  Selecting featured pieces ({len(curated)} parallel calls)…")
    sel_results = L.run_parallel([
        (lambda g=g: _select(g, found[g["key"]]["records"])) for g in curated
    ])

    # Deterministic fixups. The model SUGGESTS; Python decides. pick_ids drops
    # hallucinated ids and tops up from the real pool.
    used_ids, final_ids = set(), {}
    for group, sel in zip(curated, sel_results):
        recs = found[group["key"]]["records"]
        sel = sel if isinstance(sel, dict) else {}
        if "error" in sel:
            print(f"   ! {group['title']}: selection failed — {sel['error']}")
        exclude = used_ids if group.get("cross_slide_dedupe") else None
        ids = L.pick_ids(sel.get("entry_ids"), recs, group["want"],
                         max_ids=group.get("max_shown", 5), exclude=exclude)
        if group.get("dedupe_company"):
            seen_co, kept = set(), []
            by_id = {r["entry_id"]: r for r in recs}
            for eid in ids:
                co = (by_id.get(eid, {}).get("company_name") or eid).lower()
                if co not in seen_co:
                    seen_co.add(co)
                    kept.append(eid)
            if len(kept) < len(ids):
                print(f"   ! {group['title']}: dropped "
                      f"{len(ids) - len(kept)} same-company pick(s)")
            ids = kept
        used_ids.update(ids)
        final_ids[group["key"]] = ids
        print(f"   {group['title'][:34]:34} {ids}")

    # ── Step 6 — callouts, in parallel ──────────────────────────────────────
    print("\nStep 6  Writing callouts…")

    def _callout_job(group):
        ids = set(final_ids.get(group["key"], []))
        recs = [r for r in found[group["key"]]["records"]
                if r.get("entry_id") in ids]
        return _callout(group, recs, len(found[group["key"]]["records"]),
                        found[group["key"]]["cap_hit"])

    callouts = {}
    call_results = L.run_parallel([(lambda g=g: _callout_job(g)) for g in curated])
    for group, cdata in zip(curated, call_results):
        cdata = cdata if isinstance(cdata, dict) else {}
        if "error" in cdata:
            print(f"   ! {group['title']}: callout failed — {cdata['error']}")
        # fit_text trims to WHOLE SENTENCES — never a mid-word ellipsis.
        text = L.fit_text(L.as_text(cdata.get("callout")),
                          group.get("callout_limit", 374))
        callouts[group["key"]] = text
        print(f"   {group['title'][:34]:34} {len(text):>4} chars")

    # ── Step 7 — synthesis: the LAST model call, reading finished callouts ──
    print("\nStep 7  Final synthesis…")
    findings = [f"- {found[k]['group']['title']}: {callouts.get(k, '')}"
                for k in SYNTH_GROUPS if found.get(k, {}).get("records")]
    if not findings:
        findings = ["(no activity in this period)"]
    synth = _synthesize(period_label, findings)
    if "error" in synth:
        print(f"   ! synthesis failed — {synth['error']}")
    synth_col1 = L.cap_words(L.as_text(synth.get("column1")) or "No findings.",
                             SYNTH_MAX_WORDS)
    synth_col2 = L.cap_words(L.as_text(synth.get("column2")) or "No findings.",
                             SYNTH_MAX_WORDS)

    # ── Step 8 — assemble and build the deck ────────────────────────────────
    print("\nStep 8  Building the deck…")
    slides = []
    for item in DECK_PLAN:
        t = item["type"]
        title = (item.get("title") or "").replace("{client}", CLIENT) \
                                        .replace("{period}", period_label)
        if t == "title":
            slides.append({"type": "title",
                           "data": {"title": title, "date": period_label}})
        elif t == "agenda":
            slides.append({"type": "agenda",
                           "data": {"sections": item.get("sections") or []}})
        elif t == "newSection":
            slides.append({"type": "newSection", "data": {"title": title}})
        elif t == "needToKnow":
            slides.append({"type": "needToKnow", "data": {
                "title1": SYNTH_TITLE1.replace("{period}", period_label),
                "text1": synth_col1,
                "title2": SYNTH_TITLE2.replace("{period}", period_label),
                "text2": synth_col2}})
        elif t == "closing":
            slides.append({"type": "closing", "data": {}})
        elif t == "entry_ids":
            key = item.get("group")
            if not key or key not in found:
                print(f"   ! slide {title!r} has no group wired — skipped")
                continue
            ids = final_ids.get(key, [])
            if not ids:
                print(f"   ! {title}: no entries — slide skipped")
                continue
            text = callouts.get(key, "")
            # The builder holds SLIDE_CAP entries. Overflow becomes "(cont.)"
            # slides that repeat the same callout verbatim.
            chunks = (L.chunk_ids(ids, size=SLIDE_CAP) if item.get("chunk")
                      else [ids[:SLIDE_CAP]])
            for i, chunk in enumerate(chunks):
                slides.append({"type": "entry_ids", "data": {
                    "slideTitle": title + (" (cont.)" if i else ""),
                    "entryIds": chunk, "insight": text}})
        else:
            print(f"   ! unsupported slide type {t!r} — skipped")

    print(f"   {len(slides)} slides")
    deck_title = ("{client} Competitor Ads — {period}"
                  .replace("{client}", CLIENT).replace("{period}", period_label))
    result = build_deck_default(deck_title=deck_title, slides=slides)

    pptx_name = ("SupplyHouse_Competitor_Ads_{month_year}.pptx"
                 .replace("{client}", CLIENT.replace(" ", "_"))
                 .replace("{stamp}", stamp).replace("{mmddyy}", mmddyy)
                 .replace("{month_year}", month_year).replace("{period}", period_label))
    try:
        saved = L.save_pptx(result, OUTPUT_DIR / pptx_name)
    except RuntimeError as exc:
        print(f"ERROR: {exc}")
        print("       Check PPT_BUILDER_LOGIN / PPT_BUILDER_PASSWORD in .env and "
              "that csresearchhub.com is reachable.")
        return 1
    print(f"\n  Deck:  {saved}")

    # ── Email — opt-in only. A real send has inbox-facing consequences, so it
    #    happens only when the env var is present at run time. ────────────────
    if EMAIL_TO:
        report_name = "{client} Competitor Ads".replace("{client}", CLIENT)
        print(f"\nEmailing deliverables to {EMAIL_TO}…")
        res = L.notify_report_ready(report_name=report_name,
                                    period_label=period_label,
                                    attachment_paths=[saved],
                                    to_addr=EMAIL_TO)
        if res.get("status") == "sent":
            print(f"   sent (message_id={res.get('message_id')})")
        else:
            print(f"   !! email FAILED: {res.get('error')} — files are still "
                  f"saved locally, nothing lost")
    else:
        print("\nSkipped emailing — SH_EMAIL_TO is not set. Files saved locally only.")

    print("\n!! This pipeline has ENGINEER NOTES in its docstring — bespoke work "
          "is still required before it is production-ready.")
    print("\nDone.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
