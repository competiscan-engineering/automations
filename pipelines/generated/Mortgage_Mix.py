def _window():
    """(start, end). The env vars win; then a fixed range when this report
    has one; otherwise cadence and anchor decide. prior_complete is reproducible:
    running it again tomorrow covers the same dates."""
    if PERIOD_START:
        s = date.fromisoformat(PERIOD_START)
        if PERIOD_END:
            return s, date.fromisoformat(PERIOD_END)
        return s, (s + timedelta(days=7) if CADENCE == "week" else _month_end(s))
    today = date.today()
    if CADENCE == "week":
        if ANCHOR == "rolling":
            return today - timedelta(days=7), today
        monday = today - timedelta(days=today.weekday())
        return monday - timedelta(days=7), monday
    if ANCHOR == "rolling":
        return today - timedelta(days=30), today
    prev_end = today.replace(day=1) - timedelta(days=1)
    return prev_end.replace(day=1), prev_end


def _month_end(d):
    nxt = (d.replace(day=28) + timedelta(days=4)).replace(day=1)
    return nxt - timedelta(days=1)


def _quarter(entry_id):
    """entry_id is YYYY-MM-DD-NNNN, and that date is search_date — the date the
    piece itself carries."""
    try:
        y, m = str(entry_id).split("-")[:2]
        return f"{int(y)} Q{(int(m) - 1) // 3 + 1}"
    except (ValueError, TypeError):
        return ""


def _dedup(records):
    """product_id is the archive's primary key, so it is what identifies a piece.
    A row with no entry_id is dropped: it cannot go on a slide and it cannot be
    looked up in the database, so it has nowhere to go."""
    seen, out = set(), []
    for r in records:
        pid = r.get("product_id")
        if pid in seen or not r.get("entry_id"):
            continue
        seen.add(pid)
        out.append(r)
    return out


def _theme(record):
    """A coarse creative fingerprint: company plus the first few headline words.
    Stops one recycled evergreen ad from filling every slot on a slide."""
    co = (record.get("company") or "").lower().strip()
    head = re.sub(r"[^a-z0-9 ]", "",
                  (record.get("product_headline") or "").lower())
    return f"{co}|{' '.join(head.split()[:6])}"


def _filter(records, sec):
    """The narrowings the archive cannot express as filters. This is a short
    list on purpose — everything else was done server-side — and neither of
    these asks the model to do the filtering."""
    search = sec["search"]
    out = list(records)

    def report(label, before):
        if len(out) != before:
            print(f"      {label}: {before} -> {len(out)}")

    if search["collapse_repeats"]:
        n, counts, kept = len(out), {}, []
        for r in out:
            k = _theme(r)
            if counts.get(k, 0) < search["max_per_creative"]:
                counts[k] = counts.get(k, 0) + 1
                kept.append(r)
        out = kept
        report("collapse repeated creative", n)
    return out


def _collect(sec, channel, start, end, cap):
    """Probe for the exact total, then fetch exactly that many rows.

    The probe is one cheap request at limit=1. It is not only a count: the count
    runs BEFORE the rows, so an exact, uncapped total no greater than the row
    limit is PROOF the limit cannot fill, and that proof is what lets the server
    drive the row query off the date index instead of walking the primary key to
    the end of it. Asking for the count is what makes the fetch fast, not slow.

    Past the per-call ceiling the window is split by month and each slice repeats
    both steps. That is the only way to get a whole result set: there is no cursor
    and no offset to loop over, and narrowing is cheap because every date column
    is indexed.

    cap is a budget for this channel across every slice, so the row cap means
    what it says however many times the window is split."""
    base = CS.build_body(sec["search"], channel=channel, date_field=DATE_FIELD)
    rows, notes, resolved = [], [], None
    # cap is a budget for the whole CHANNEL, not for each slice. Spent per
    # slice, a 500-row cap would quietly become 500 rows a MONTH as soon as
    # the window splits.
    budget = cap
    archive_total = 0   # what the archive holds, before any cap of ours
    # True when a slice came back past the archive's own count cap and could not
    # be split any finer. The total is then a LOWER BOUND, and every consumer of
    # it — the printout, the state file, the deck — must say "at least N" rather
    # than quote it as a fact.
    lower_bound = False
    pending = [(start, end)]
    while pending:
        s, e = pending.pop(0)
        body = {**base, "date_from": str(s), "date_to": str(e)}
        try:
            probe = CS.count(body)
        except CS.ApiError as exc:
            notes.append(f"{channel} {s}..{e}: {exc.code} — {exc.hint()}")
            if exc.code == "quota_exceeded":
                raise
            continue
        if resolved is None:
            resolved = probe.get("resolved_filters") or {}
        total = int(probe.get("total") or 0)
        capped = bool(probe.get("total_is_capped"))
        # Counted BEFORE the row cap and the per-call ceiling touch it: this
        # is the number that reconciles against PowerSearch, and the only one
        # a write-up may state as the volume for the period.
        archive_total += total
        if not total and not capped:
            continue
        if capped or total > CS.LIMIT_MAX:
            parts = CS.month_slices(s, e)
            if len(parts) > 1:
                pending = parts + pending
                continue
            # One month and still past the ceiling. Say so, rather than let a
            # truncated slice look complete.
            notes.append(
                f"{s}..{e}: {'past the count cap' if capped else total} in a "
                f"single month, over the {CS.LIMIT_MAX:,}-row ceiling — took the "
                f"newest {CS.LIMIT_MAX:,}. Narrow this section.")
            total = CS.LIMIT_MAX
            lower_bound = lower_bound or capped
        want = min(total, budget)
        if want < total:
            notes.append(f"{channel} {s}..{e}: {total} matched, the row cap "
                         f"held it to {want}.")
        if not want:
            # Budget spent. Stop probing the slices still pending rather
            # than paying for counts whose rows would be thrown away.
            notes.append(f"{channel}: row cap of {cap} reached — "
                         f"{len(pending) + 1} window slice(s) not fetched.")
            break
        try:
            res = CS.search({**body, "limit": want, "include_total": True,
                             "sort": "date"})
        except CS.ApiError as exc:
            notes.append(f"{channel} {s}..{e}: {exc.code} — {exc.hint()}")
            if exc.code == "quota_exceeded":
                raise
            continue
        got = res.get("results") or []
        rows.extend(got)
        budget -= len(got)
        if res.get("truncated") and want == total:
            # limit == the exact total, so this should not happen. When it does,
            # the archive gained matching rows between the probe and the fetch.
            notes.append(f"{channel} {s}..{e}: fetch came back truncated even "
                         f"at the exact total — the archive gained rows "
                         f"mid-run.")
    return rows, notes, resolved or {}, archive_total, lower_bound


def _lookup(entry_ids):
    """entry_ids -> the worksheet values that are NOT on the API search row.
    Only printing comes here; filtering never does. Only ids that have both a
    document and a primary-company mapping come back — the query inner-joins
    them."""
    if not entry_ids:
        return {}
    df = _run_sql(XH.build_query(entry_ids))
    if df is None or getattr(df, "empty", True):
        return {}
    text_cols = {"additional_companies", "sectors", "categories",
                 "sub_categories", "states", "ages", "incomes",
                 "primary_company", "product_name", "product_headline",
                 "media_channel", "mailing_type", "entry_id"}

    def clean(k, v):
        # pandas types GROUP_CONCAT oddly: all-NULL becomes NaN and all-numeric
        # becomes float. Flag columns MUST stay ints — "0" is truthy and would
        # flip Pre-Screen.
        if v is None or (isinstance(v, float) and v != v):
            return None
        return str(v) if k in text_cols else v

    raw = [{k: clean(k, v) for k, v in rec.items()}
           for rec in df.to_dict("records")]
    out = {}
    for row, src in zip(XH.complete_rows(raw), raw):
        out[src.get("entry_id")] = row
    return out


# ── Reading a piece ──────────────────────────────────────────────────────────
# entry_id -> the words read off its scanned pages, for pieces already
# fetched. Kept module-level because two stages want it: the worksheet
# column prints it and the write-up reads it, and neither should pay for
# the other's pieces twice.
OCR = {}          # entry_id -> text
OCR_TRIED = set() # asked already, hit or miss, so we never ask twice


def _read_ocr(entry_ids, cap=None):
    """Fill OCR for these ids. Returns notes worth printing.

    GET /v1/ocr takes one entry_id and there is no batch form — each
    call is two keyed lookups, so a loop costs what a batch would. What a
    loop does cost is ONE QUOTA UNIT PER PIECE, which is the whole reason
    cap exists and the reason the caller is told when it bit rather than
    being handed a quietly short dictionary."""
    want = [e for e in dict.fromkeys(entry_ids) if e and e not in OCR_TRIED]
    if not want:
        return []
    tried = want[:cap] if cap else want
    got, notes = CS.ocr_texts(tried)
    OCR.update(got)
    OCR_TRIED.update(tried)
    if cap and len(want) > cap:
        notes.insert(0, f"{len(want)} pieces to read, capped at {cap}. Raise OCR_ROW_CAP or narrow the section.")
    return notes



def _row(record, sql, columns):
    """Build one worksheet row. A database value wins when we have one;
    otherwise the value comes off the API search row or is derived from it. A
    column with no source renders blank rather than being guessed at."""
    out = {}
    for col in columns:
        field = API_FIELD.get(col)
        if sql and sql.get(col):
            out[col] = sql[col]
        elif field:
            val = record.get(field)
            out[col] = L.clean_cell(val)
        elif col == "Quarter":
            out[col] = _quarter(record.get("entry_id"))
        else:
            out[col] = ""
    out["entry_id"] = record.get("entry_id") or ""
    out["pid"] = record.get("product_id") or ""
    out["pdf_url"] = record.get("pdf_url") or ""
    return out


