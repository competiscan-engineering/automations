def stage_select(found):
    """Choose which pieces go on each slide. Returns the ids and the model's
    stated reason, and writes NO prose — every sentence that reaches a deck is
    written in stage_deliver, after a person has had the chance to change
    this list."""
    picked = [s for s in SECTIONS if s["feature"]]
    print(f"\nStep 5  Choosing pieces ({len(picked)} parallel calls)…")
    shortlists = {}
    for sec in picked:
        recs, note = _shortlist(found[sec["id"]]["records"], CANDIDATE_CAP)
        shortlists[sec["id"]] = recs
        if note:
            print(f"   ! {sec['title']}: {note}")
    choices = L.run_parallel(
        [(lambda s=s: _choose(s, shortlists[s["id"]])) for s in picked])

    # The model suggests; Python decides. _eligible says what this section
    # may still use, and pick_ids drops anything invented and tops the list
    # up from the real pool. The ranked result is then split in two: the
    # slide, and the reserve standing behind it.
    used, final, reserve, why = set(), {}, {}, {}
    for sec, choice in zip(picked, choices):
        records = found[sec["id"]]["records"]
        by_id = {r["entry_id"]: r for r in records if r.get("entry_id")}
        choice = choice if isinstance(choice, dict) else {}
        if "error" in choice:
            print(f"   ! {sec['title']}: choosing failed — {choice['error']}")
        why[sec["id"]] = L.as_text(choice.get("reasoning"))[:400]
        want = sec["count"] * RESERVE_FACTOR
        pool = _eligible(records, used if sec["never_reuse"] else (), ())
        ranked = L.pick_ids(choice.get("entry_ids"), pool, want,
                            max_ids=want)

        # Walk the ranking once. A piece goes on the slide if there is room
        # and its company is not already up there; everything else keeps its
        # rank and waits. So one_per_company no longer costs the slide a
        # slot — it moves the piece down the list instead of deleting it.
        ids, rest, seen_co = [], [], set()
        for eid in ranked:
            co = (by_id.get(eid, {}).get("company") or eid).lower()
            room = len(ids) < sec["count"]
            clash = sec["one_per_company"] and co in seen_co
            if room and not clash:
                seen_co.add(co)
                ids.append(eid)
            else:
                rest.append(eid)

        # Only what is ON a slide is off-limits to the other sections. A
        # reserve piece has not been spent, so holding it must not quietly
        # remove it from another section's pool.
        used.update(ids)
        final[sec["id"]] = ids
        reserve[sec["id"]] = rest
        print(f"   {sec['title'][:34]:34} {len(ids)} piece(s) {ids}"
              + (f"  +{len(rest)} held in reserve" if rest else ""))
    return final, reserve, why


def stage_deliver(found, sql_rows, final, xlsx_path, start, end, lab):
    """Read the chosen pieces, write the prose, build the deck, email it.

    EVERY model call that produces a sentence lives on this side of the line. In
    a two-phase run `final` is the list a person approved, so the paragraph under
    a slide can only ever describe pieces that survived that review."""
    picked = [s for s in SECTIONS if s["feature"]]

    # Read only the pieces that were actually chosen. This is where the
    # scanned page earns its request: 3-5 pieces a section, against every
    # candidate if it were done before the pick.
    chosen_ids = [e for ids in final.values() for e in ids]
    if chosen_ids:
        print(f"\nStep 5b Reading {len(chosen_ids)} chosen piece(s)…")
        for note in _read_ocr(chosen_ids):
            print(f"   ! {note}")
        print(f"   {sum(1 for e in chosen_ids if OCR.get(e))} of {len(chosen_ids)} had text on file")

    # ── Step 6 — the write-ups (parallel model calls) ───────────────────────
    print("\nStep 6  Write-ups…")

    def writeup_job(sec):
        ids = set(final.get(sec["id"], []))
        chosen = [r for r in found[sec["id"]]["records"]
                  if r.get("entry_id") in ids]
        return _writeup(sec, chosen, found[sec["id"]]["archive_total"],
                        found[sec["id"]].get("at_least"))

    texts = {}
    results = L.run_parallel([(lambda s=s: writeup_job(s)) for s in picked])
    for sec, data in zip(picked, results):
        data = data if isinstance(data, dict) else {}
        if "error" in data:
            print(f"   ! {sec['title']}: write-up failed — {data['error']}")
        # fit_text trims to whole sentences — never a mid-word ellipsis.
        text = L.fit_text(L.as_text(data.get("callout")), sec["callout_limit"])
        texts[sec["id"]] = text
        print(f"   {sec['title'][:34]:34} {len(text):>4} chars")

    # ── Step 7 — the summary: the LAST model call ───────────────────────────
    print("\nStep 7  Summary slide…")
    lines = [f"- {s['title']}: {texts.get(s['id'], '')}"
             for s in picked if found[s["id"]]["records"]]
    if not lines:
        lines = ["(nothing was found this period)"]
    summary = _summary(lab["period"], lines)
    if "error" in summary:
        print(f"   ! summary failed — {summary['error']}")
    sum1 = L.cap_words(L.as_text(summary.get("column1")) or "No findings.",
                       SUMMARY_MAX_WORDS)
    sum2 = L.cap_words(L.as_text(summary.get("column2")) or "No findings.",
                       SUMMARY_MAX_WORDS)

    # ── Step 8 — build the deck ─────────────────────────────────────────────
    print("\nStep 8  Deck…")
    slides = []
    slides.append({"type": "title",
                   "data": {"title": CLIENT, "date": lab["period"]}})
    headings = []
    for sec in SECTIONS:
        h = (sec.get("heading") or "").strip()
        if h and h not in headings and sec["feature"]:
            headings.append(h)
    if headings:
        slides.append({"type": "agenda", "data": {"sections": headings}})
    slides.append({"type": "needToKnow", "data": {
        "title1": SUMMARY_TITLE1.replace("{period}", lab["period"]),
        "text1": sum1,
        "title2": SUMMARY_TITLE2.replace("{period}", lab["period"]),
        "text2": sum2}})

    current = None
    for sec in SECTIONS:
        if not sec["feature"]:
            continue
        h = (sec.get("heading") or "").strip()
        if h and h != current:
            slides.append({"type": "newSection", "data": {"title": h}})
            current = h
        ids = final.get(sec["id"], [])
        if not ids:
            print(f"   ! {sec['title']}: nothing to show — slide skipped")
            continue
        text = texts.get(sec["id"], "")
        # The builder holds SLIDE_CAP entries, so overflow always rolls onto
        # "(cont.)" slides carrying the same write-up.
        for i, chunk in enumerate(L.chunk_ids(ids, size=SLIDE_CAP)):
            slides.append({"type": "entry_ids", "data": {
                "slideTitle": sec["title"] + (" (cont.)" if i else ""),
                "entryIds": chunk, "insight": text}})

    slides.append({"type": "closing", "data": {}})

    print(f"   {len(slides)} slides")
    deck_title = ("{client} — {period}"
                  .replace("{client}", CLIENT)
                  .replace("{period}", lab["period"]))
    result = build_deck_default(deck_title=deck_title, slides=slides)

    pptx_name = ("{client}_{month_year}.pptx"
                 .replace("{client}", CLIENT.replace(" ", "_"))
                 .replace("{stamp}", lab["stamp"])
                 .replace("{mmddyy}", lab["mmddyy"])
                 .replace("{month_year}", lab["month_year"])
                 .replace("{period}", lab["period"]))
    try:
        saved = L.save_pptx(result, OUTPUT_DIR / pptx_name)
    except RuntimeError as exc:
        print(f"ERROR: {exc}")
        print("       Check PPT_BUILDER_LOGIN / PPT_BUILDER_PASSWORD in .env"
              " and that csresearchhub.com is reachable.")
        if xlsx_path:
            print(f"       (The workbook was still written: {xlsx_path})")
        return 1
    print(f"\n  Deck:  {saved}")
    if xlsx_path:
        print(f"  Excel: {xlsx_path}")

    # ── Email — opt-in, and by variable NAME only. This file carries no
    #    recipient: a scheduled run reads one from the environment, and a one-off
    #    run gets one from whoever started it. Nothing is emailed when neither
    #    is set, and the files are on disk either way. ─────────────────────────
    if EMAIL_TO:
        print(f"\nEmailing deliverables to {EMAIL_TO}…")
        res = L.notify_report_ready(
            report_name=f"{CLIENT} report", period_label=lab["period"],
            attachment_paths=[a for a in (saved, xlsx_path) if a], to_addr=EMAIL_TO)
        if res.get("status") == "sent":
            print(f"   sent (message_id={res.get('message_id')})")
        else:
            print(f"   !! email FAILED: {res.get('error')} — the files are"
                  f" still saved locally, nothing is lost")
    else:
        print("\nNothing emailed — no recipient was set. The files are saved locally.")

    print("\nDone.")
    return 0


def stage_resume(args):
    """Rebuild the first half of a run from its state file. No searching.

    The SECTIONS table in this file wins over the copy in the state, so a fix
    made between the two halves takes effect. Only the records come from the
    state — those are what was fetched, and refetching them is the one thing
    this phase must never do."""
    state = _state_read(args.state)
    print(f"  resuming {args.state} — written {state.get('written_at')}")
    approved = {}
    if args.approved:
        approved = json.loads(
            Path(args.approved).read_text(encoding="utf-8"))
    by_id = {x["id"]: x for x in (state.get("sections") or [])}
    found, final = {}, {}
    for sec in SECTIONS:
        st = by_id.get(sec["id"])
        if st is None:
            print(f"   ! {sec['title']}: not in the state file — skipped.")
            continue
        records = st.get("records") or []
        found[sec["id"]] = {
            "sec": sec, "records": records,
            "fetched": st.get("fetched") or len(records),
            "archive_total": st.get("archive_total") or 0,
            "at_least": bool(st.get("at_least")),
        }
        if not sec["feature"]:
            continue
        found[sec["id"]]["reserve"] = list(st.get("reserve") or [])
        want = list(dict.fromkeys(approved.get(sec["id"])
                                  if sec["id"] in approved
                                  else (st.get("picks") or [])))
        have = {r.get("entry_id") for r in records}
        keep = [e for e in want if e in have]
        if len(keep) != len(want):
            print(f"   ! {sec['title']}: dropped {len(want) - len(keep)}"
                  f" approved id(s) that are not in this run's records.")
        final[sec["id"]] = keep
    # Text already read in the first half. Marked as tried too, so the
    # second half does not pay a second request for a piece it has.
    OCR.update(state.get("ocr") or {})
    OCR_TRIED.update(OCR)
    xlsx = state.get("workbook")
    return found, state.get("sql_rows") or {}, final, (Path(xlsx) if xlsx else None)


def main() -> int:
    args = _parse_args()
    if args.phase == "replace":
        return _replace(args)
    if args.phase in ("pick", "build") and not args.state:
        # Checked before anything is spent, not after the searching is done.
        print(f"ERROR: --phase {args.phase} needs --state — the file the two"
              f" halves of the run hand over through.")
        return 1

    start, end = _window()
    lab = _labels(start, end)
    OUTPUT_DIR.mkdir(parents=True, exist_ok=True)
    print(f"{CLIENT} — {lab['period']}")
    print(f"  window {start} .. {end}  (bounded server-side by {DATE_FIELD})")
    print(f"  mode --only={args.only}"
          + (f" --phase={args.phase}" if args.phase != "all" else "")
          + (f" --limit={args.limit}" if args.limit else ""))

    if args.phase == "build":
        found, sql_rows, final, xlsx_path = stage_resume(args)
        return stage_deliver(found, sql_rows, final, xlsx_path, start, end,
                             lab)

    found, sql_rows = stage_search(args, start, end)
    if found is None:
        return 1

    def save_state(final, reserve, why, xlsx_path):
        if args.state:
            _state_write(args.state, start, end, lab, found, sql_rows, final,
                         reserve, why, xlsx_path)

    if args.only == "search":
        print_counts(found)
        save_state({}, {}, {}, None)
        return 0

    xlsx_path = stage_workbook(found, sql_rows, start, end, lab)
    if args.only == "excel":
        save_state({}, {}, {}, xlsx_path)
        return 0

    final, reserve, why = stage_select(found)
    if args.phase == "pick":
        save_state(final, reserve, why, xlsx_path)
        print("\nPaused. Approve the picks, then run --phase build with the"
              " state file above.")
        return 0
    return stage_deliver(found, sql_rows, final, xlsx_path, start, end, lab)


if __name__ == "__main__":
    sys.exit(main())
