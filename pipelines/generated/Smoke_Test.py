# ── Helpers ──────────────────────────────────────────────────────────────────
def _parse_args():
    p = argparse.ArgumentParser(description=f"{CLIENT} report")
    p.add_argument("--only", default="all", choices=["search", "excel", "deck", "all"],
                   help="Stop after a stage — cheap iteration while testing.")
    p.add_argument("--limit", type=int, default=None,
                   help="Override every search limit (small = fast test).")
    return p.parse_args()


def _window():
    """(start, end). The env vars win; otherwise cadence and anchor decide.
    prior_complete is reproducible: running it again tomorrow covers the same
    dates."""
    if PERIOD_START:
        s = date.fromisoformat(PERIOD_START)
        if PERIOD_END:
            return s, date.fromisoformat(PERIOD_END)
        return s, (s + timedelta(days=7) if CADENCE == "week" else _month_end(s))
    today = date.today()
    if CADENCE == "week":
        if ANCHOR == "rolling":
            return today - timedelta(days=7), today
        monday = today - timedelta(days=today.weekday())
        return monday - timedelta(days=7), monday
    if ANCHOR == "rolling":
        return today - timedelta(days=30), today
    prev_end = today.replace(day=1) - timedelta(days=1)
    return prev_end.replace(day=1), prev_end


def _month_end(d):
    nxt = (d.replace(day=28) + timedelta(days=4)).replace(day=1)
    return nxt - timedelta(days=1)


def _ordinal(n):
    suffix = "th" if 11 <= n % 100 <= 13 else {1: "st", 2: "nd",
                                               3: "rd"}.get(n % 10, "th")
    return f"{n}{suffix}"


def _entry_date(entry_id):
    """entry_id is YYYY-MM-DD-NNNN. This is the MAILED/CAPTURED date — not
    approved_date and not added_to_database. The three disagree."""
    try:
        y, m, d = str(entry_id).split("-")[:3]
        return date(int(y), int(m), int(d))
    except (ValueError, AttributeError):
        return None


def _quarter(entry_id):
    d = _entry_date(entry_id)
    return f"{d.year} Q{(d.month - 1) // 3 + 1}" if d else ""


def _dedup(records):
    seen, out = set(), []
    for r in records:
        eid = r.get("entry_id")
        if eid and eid not in seen:
            seen.add(eid)
            out.append(r)
    return out


def _theme(record):
    """A coarse creative fingerprint: company plus the first few headline words.
    Stops one recycled evergreen ad from filling every slot on a slide."""
    co = (record.get("company_name") or "").lower().strip()
    head = re.sub(r"[^a-z0-9 ]", "", (record.get("headline") or "").lower())
    return f"{co}|{' '.join(head.split()[:6])}"


def _filter(records, sec, subcats=None):
    """The section's narrowing rules, in a fixed order. None of these ask the
    model to do the filtering."""
    out = list(records)

    def report(label, before):
        if len(out) != before:
            print(f"      {label}: {before} -> {len(out)}")

    if sec["company_must_match"]:
        n = len(out)
        out = [r for r in out
               if re.search(sec["company_must_match"],
                            r.get("company_name") or "", re.I)]
        report("company must match", n)
    if sec["company_must_not_match"]:
        n = len(out)
        out = [r for r in out
               if not re.search(sec["company_must_not_match"],
                                r.get("company_name") or "", re.I)]
        report("company must not match", n)
    if sec["subcat_include"] or sec["subcat_exclude"]:
        n, kept = len(out), []
        for r in out:
            tags = (subcats or {}).get(r.get("entry_id"), "").lower()
            # A blank tag matches nothing on purpose: dropping a piece we cannot
            # verify beats putting it in the wrong section.
            if not tags:
                continue
            if any(k in tags for k in sec["subcat_exclude"]):
                continue
            if sec["subcat_include"] and not any(k in tags
                                                for k in sec["subcat_include"]):
                continue
            kept.append(r)
        out = kept
        report("sub-category", n)
    if sec["collapse_repeats"]:
        n, counts, kept = len(out), {}, []
        for r in out:
            k = _theme(r)
            if counts.get(k, 0) < sec["max_per_creative"]:
                counts[k] = counts.get(k, 0) + 1
                kept.append(r)
        out = kept
        report("collapse repeated creative", n)
    return out


def _search(sec, channel, limit):
    """One call, one channel. Fanning out per channel multiplies the per-call cap.
    Callers MUST keep this sequential — see the guardrails above."""
    kwargs = {"media_channels": [channel], "limit": limit}
    if sec["sectors"]:
        kwargs["sectors"] = sec["sectors"]
    if sec["companies"]:
        kwargs["company_names"] = sec["companies"]
    if sec["keyword"]:
        kwargs["keyword"] = sec["keyword"]
    if sec["audience"]:
        kwargs["audience"] = sec["audience"]
    try:
        res = search_archive(**kwargs)
    except Exception as exc:  # a dead tunnel must not kill the whole run
        return [], False, str(exc)
    if res and isinstance(res[0], dict) and "error" in res[0]:
        return [], False, res[0]["error"]
    rows = [r for r in (res or []) if r.get("entry_id")]
    return rows, len(rows) >= limit, None


def _lookup(entry_ids):
    """entry_ids -> canonical column values from the database, keyed by
    entry_id. Only ids that have both a document and a primary-company
    mapping come back — the query inner-joins them."""
    if not entry_ids:
        return {}
    df = _run_sql(XH.build_query(entry_ids))
    if df is None or getattr(df, "empty", True):
        return {}
    text_cols = {"additional_companies", "sectors", "categories",
                 "sub_categories", "states", "ages", "incomes",
                 "primary_company", "product_name", "product_headline",
                 "media_channel", "mailing_type", "entry_id"}

    def clean(k, v):
        # pandas types GROUP_CONCAT oddly: all-NULL becomes NaN and all-numeric
        # becomes float. Flag columns MUST stay ints — "0" is truthy and would
        # flip Pre-Screen.
        if v is None or (isinstance(v, float) and v != v):
            return None
        return str(v) if k in text_cols else v

    raw = [{k: clean(k, v) for k, v in rec.items()}
           for rec in df.to_dict("records")]
    out = {}
    for row, src in zip(XH.complete_rows(raw), raw):
        row["pid"] = src.get("product_id", "")
        row["_subcats"] = src.get("sub_categories") or ""
        out[src.get("entry_id")] = row
    return out


def _row(record, sql, columns):
    """Build one worksheet row. A database value wins when we have one;
    otherwise the value comes off the search result or is derived from it. A
    column with no source renders blank rather than being guessed at."""
    out = {}
    for col in columns:
        if sql and col in sql:
            out[col] = sql.get(col) or ""
        elif col == "EntryID":
            out[col] = record.get("entry_id") or ""
        elif col == "Primary Company":
            out[col] = record.get("company_name") or ""
        elif col == "Media Channel":
            out[col] = record.get("media_channel") or ""
        elif col == "State/Province":
            out[col] = record.get("state") or ""
        elif col == "Headline":
            out[col] = L.clean_cell(record.get("headline"))
        elif col == "OCR Text":
            out[col] = L.clean_cell(record.get("ocr_text"))[:900]
        elif col == "Quarter":
            out[col] = _quarter(record.get("entry_id"))
        else:
            out[col] = ""
    out["entry_id"] = record.get("entry_id") or ""
    out["pid"] = (sql or {}).get("pid") or record.get("product_id") or ""
    return out


